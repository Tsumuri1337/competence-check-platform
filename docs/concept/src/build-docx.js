let figNo = 0, tabNo = 0;
function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}
function FIG(file, caption, page, opts = {}) {
  figNo++;
  const { w, h } = pngSize(file);
  const maxW = (opts.maxW || page.imgW) / 2.54 * 96;
  const maxH = (opts.maxH || page.imgH) / 2.54 * 96;
  const k = Math.min(maxW / w, maxH / h);
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 120, after: 60 },
      children: [new ImageRun({ type: "png", data: fs.readFileSync(file), transformation: { width: Math.round(w * k), height: Math.round(h * k) } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: [new TextRun({ text: `Рисунок ${figNo} — ${caption}`, size: 22 })] }),
  ];
}

// Схема из двух частей (соединитель ГОСТ 19.701) рядом на одной странице, единый масштаб.
function FIG2(base, caption, page) {
  figNo++;
  const fa = D("p-" + base + "-a"), fb = D("p-" + base + "-b");
  const a = pngSize(fa), b = pngSize(fb);
  const cm = 96 / 2.54;
  const k = Math.min((page.imgW - 0.6) * cm / (a.w + b.w), 22 * cm / Math.max(a.h, b.h));
  const nb = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  const nbs = { top: nb, bottom: nb, left: nb, right: nb };
  const total = page.w;
  const wa = Math.round(total * a.w / (a.w + b.w));
  const cell = (f, s, w) => new TableCell({ borders: nbs, width: { size: w, type: WidthType.DXA }, verticalAlign: VerticalAlign.TOP,
    children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new ImageRun({ type: "png", data: fs.readFileSync(f), transformation: { width: Math.round(s.w * k), height: Math.round(s.h * k) } })] })] });
  return [
    new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: [wa, total - wa], borders: { ...nbs, insideHorizontal: nb, insideVertical: nb },
      rows: [new TableRow({ cantSplit: true, children: [cell(fa, a, wa), cell(fb, b, total - wa)] })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 80, after: 200 }, children: [new TextRun({ text: `Рисунок ${figNo} — ${caption}`, size: 22 })] }),
  ];
}
